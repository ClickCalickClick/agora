#!/usr/bin/env python3
"""Write po/POTFILES.in: every file that may hold translatable strings.

Meson has no glob, so this list is generated. Run it after adding or removing
Rust sources, Blueprint files or translatable data files:

    build-aux/gen-potfiles.py          # rewrite po/POTFILES.in
    build-aux/gen-potfiles.py --check  # exit 1 if po/POTFILES.in is stale

The Meson test `potfiles` runs the --check form.

Language handling (xgettext from gettext >= 0.24 is assumed):
- *.rs is recognized natively as Rust (gettext, ngettext, pgettext, ...).
- *.blp has no xgettext parser; per the Blueprint docs it is extracted with
  the C parser and the keywords `_` and `C_:1c,2`, which Meson's
  `preset: 'glib'` passes. xgettext warns that the extension is unknown and
  falls back to C; the warning is expected.
- *.desktop.in.in, *.metainfo.xml.in.in and *.gschema.xml.in are recognized by
  their inner extension.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "po" / "POTFILES.in"

DATA_FILES = [
    "data/io.github.ClickCalickClick.Agora.desktop.in.in",
    "data/io.github.ClickCalickClick.Agora.metainfo.xml.in.in",
    "data/io.github.ClickCalickClick.Agora.gschema.xml.in",
]

SCANS = [
    ("crates/agora-app/src", "*.rs"),
    ("data/resources/ui", "*.blp"),
]


def collect() -> list[str]:
    files = [f for f in DATA_FILES if (ROOT / f).exists()]
    for directory, pattern in SCANS:
        base = ROOT / directory
        if base.is_dir():
            files += sorted(p.relative_to(ROOT).as_posix() for p in base.rglob(pattern) if p.is_file())
    return files


def render(files: list[str]) -> str:
    header = "# Generated by build-aux/gen-potfiles.py. Do not edit by hand.\n"
    return header + "".join(f + "\n" for f in files)


def main() -> int:
    text = render(collect())
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("po/POTFILES.in is out of date; run build-aux/gen-potfiles.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
